export const extractFlagAndName = (fullName: string) => {
  const emojiRegex = /([\uD83C][\uDDE6-\uDDFF][\uD83C][\uDDE6-\uDDFF])|([\u2700-\u27BF]|[\uE000-\uF8FF]|\uD83C[\uDC00-\uDFFF]|\uD83D[\uDC00-\uDFFF]|[\u2011-\u26FF]|\uD83E[\uDD10-\uDDFF])/g;
  const match = fullName.match(emojiRegex);
  if (match && match.length > 0) {
    const flag = match[0];
    const nameWithoutFlag = fullName.replace(flag, "").trim();
    return { flag, name: nameWithoutFlag };
  }
  return { flag: null, name: fullName };
};

export const getTeamFlag = (team?: { name: string; logo_url?: string | null } | null) => {
  if (!team) return null;
  if (team.logo_url) {
    return team.logo_url;
  }
  const { flag } = extractFlagAndName(team.name);
  if (flag) return flag;
  return null;
};

export function getFlagImgUrl(emoji: string | null | undefined): string | null {
  if (!emoji) return null;
  if (emoji === "🏴󠁧󠁢󠁳󠁣󠁴󠁿") {
    return "https://flagcdn.com/w40/gb-sct.png";
  }
  const chars = [...emoji];
  if (chars.length < 2) return null;
  
  const codePoints = chars.map(c => c.codePointAt(0));
  const countryCode = codePoints
    .map(cp => {
      if (cp && cp >= 0x1F1E6 && cp <= 0x1F1FF) {
        return String.fromCharCode(cp - 0x1F1E6 + 65);
      }
      return "";
    })
    .join("")
    .toLowerCase();
    
  if (countryCode.length === 2) {
    return `https://flagcdn.com/w40/${countryCode}.png`;
  }
  return null;
}
